"""드랍 아이템 등급 판별 — 고급 템만 줍기 위한 목록(사용자 지시 2026-09-15
'고급템과 저급템 목록을 전부만들고 판별').

라벨 이름 OCR 텍스트로 판별한다. 리니지 클래식 바닥 드랍 기준:
- HIGH  : 줍는다 (가치 있음)
- LOW   : 무시한다 (잡템 — 줍기 비용이 가치보다 큼)
- UNKNOWN: 줍는다 (모르는 템을 놓치는 손해 > 잡템 줍는 손해)

키워드는 부분 매칭(OCR 오독 여유)이며, 고급 키워드 우선 적용한다.
"""

# 고급 템 키워드 (이 문자열이 이름에 포함되면 HIGH)
HIGH_KEYWORDS = (
    "아데나",
    # 스크롤류
    "마법 주문서", "마법주문서", "주문서",
    # 보석/젬
    "젬스톤", "다이아몬드", "루비", "사파이어", "에메랄드", "스피넬", "오팔",
    # 귀금속/재료
    "미스릴", "오리하루콘", "플래티넘",
    # 반지/목걸이/장신구
    "반지", "목걸이", "부적",
    # 귀중 소모품
    "용기", "용혈포", "용의",
    # 네임드/희귀
    "붉은 기사", "기사의", "수정", "정령",
    # 강화 아이템(+N 감정 후 드랍)
    "+1", "+2", "+3", "+4", "+5", "+6", "+7", "+8", "+9",
)

# 저급 템 키워드 (포함되면 LOW — HIGH 키워드가 없을 때만)
LOW_KEYWORDS = (
    # 투사체
    "화살", "미늘창",
    # 몹 재료 잡템
    "가죽", "발톱", "점액", "거미줄", "젤라틴", "뼈", "해골", "심장",
    "이빨", "날개", "깃털", "비늘", "고기", "알",
    # 기본 소모품
    "빈병", "물약", "해독제",
    # 기본 방어구(순정 저렙)
    "두건", "망토", "신발", "장화", "가죽갑옷", "티셔츠", "허름한", "낡은",
    # 기본 무기(잡템)
    "장검", "도끼", "봉", "단검", "망토",
)


def tier_of(name: str) -> str:
    """라벨 이름 → 'high' | 'low' | 'unknown'."""
    if not name:
        return "unknown"
    n = name.replace(" ", "")
    for kw in HIGH_KEYWORDS:
        if kw.replace(" ", "") in n:
            return "high"
    for kw in LOW_KEYWORDS:
        if kw.replace(" ", "") in n:
            return "low"
    return "unknown"
